// Uses an isolated test server/account provided by the test runner. No seed data.
const {chromium}=require('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/');
  await page.locator('#login-form').waitFor();
  await page.screenshot({path:process.env.LOOP_ARTIFACTS+'/admin-login.png',fullPage:true});
  await page.locator('#login-form input[name=email]').fill(process.env.LOOP_TEST_EMAIL);
  await page.locator('#login-form input[name=password]').fill(process.env.LOOP_TEST_PASSWORD);
  await page.locator('#login-form input[name=code]').fill(process.env.LOOP_TEST_CODE);
  await page.locator('#login-form button[type=submit]').click();
  await page.locator('#workspace').waitFor({state:'visible'});
  if(await page.locator('#total').textContent()!=='0')throw Error('Empty real database expected');
  await page.screenshot({path:process.env.LOOP_ARTIFACTS+'/admin-overview.png',fullPage:true});
  await page.locator('#new-customer').click();
  await page.locator('#enrollment-dialog').waitFor({state:'visible'});
  await page.locator('#enrollment-form input[name=name]').fill('Browser Workflow Test');
  await page.locator('#enrollment-form input[name=phone]').fill('+27630000000');
  await page.locator('#enrollment-form button[type=submit]').click();
  await page.locator('#enrollment-result').waitFor({state:'visible'});
  const enrollment=await page.locator('#result-token').inputValue();
  if(enrollment.length<20)throw Error('Enrollment token missing');
  const enrollmentResult=await page.request.post('http://127.0.0.1:8765/api/device/enroll',{data:{enrollment_token:enrollment,model:'Isolated browser integration device',consent:true}});
  if(!enrollmentResult.ok())throw Error('Device enrollment exchange failed');
  const device=await enrollmentResult.json();
  const deviceHeaders={Authorization:'Bearer '+device.device_token};
  await page.locator('#enrollment-result button[data-close]').click();
  await page.locator('nav [data-view=devices]').click();
  await page.getByText('Browser Workflow Test',{exact:true}).waitFor();
  await page.locator('#search').fill('no matching customer');
  await page.getByText('No matching customers. Enroll your first connection to begin.',{exact:true}).waitFor();
  await page.locator('#search').fill('');
  await page.locator('button[data-device]').click();
  await page.locator('#policy-form input[name=update_window_start]').fill('03:00');
  await page.locator('#policy-form button[type=submit]').click();
  await page.locator('#device-dialog').waitFor({state:'hidden'});
  await page.locator('#fleet-policy').click();
  await page.locator('#policy-form input[name=grace_hours]').fill('36');
  await page.locator('#policy-form input[name=confirm_all]').check();
  await page.locator('#policy-form button[type=submit]').click();
  await page.locator('#device-dialog').waitFor({state:'hidden'});
  await page.locator('#banking-settings').click();
  await page.locator('#banking-form input[name=bank]').fill('Test Bank');
  await page.locator('#banking-form input[name=account_holder]').fill('Test Business');
  await page.locator('#banking-form input[name=account_number]').fill('1234567890');
  await page.locator('#banking-form input[name=branch_code]').fill('123456');
  await page.locator('#banking-form input[name=details_verified]').check();
  await page.locator('#banking-form button[type=submit]').click();
  await page.locator('#banking-dialog').waitFor({state:'hidden'});
  await page.locator('nav [data-view=messages]').click();
  await page.locator('#compose-message').click();
  await page.locator('#message-form select[name=recipient]').selectOption(device.device_id);
  await page.locator('#message-form input[name=title]').fill('Account support');
  await page.locator('#message-form textarea[name=message]').fill('Your payment claim is ready for review.');
  await page.locator('#message-form button[type=submit]').click();
  await page.locator('#message-dialog').waitFor({state:'hidden'});
  await page.getByText('0 / 1 delivered',{exact:true}).waitFor();
  const synced=await page.request.post('http://127.0.0.1:8765/api/device/sync',{headers:deviceHeaders,data:{revision:0,status:'unsupported'}});
  const signed=await synced.json();const payload=JSON.parse(Buffer.from(signed.payload,'base64').toString());
  if(payload.messages.length!==1||payload.policy.grace_hours!==36||payload.eft.account_number!=='1234567890')throw Error('Live device data did not receive admin changes');
  await page.request.post('http://127.0.0.1:8765/api/device/messages/receipt',{headers:deviceHeaders,data:{ids:[payload.messages[0].id],state:'delivered'}});
  await page.locator('#refresh').click();
  await page.getByText('1 / 1 delivered',{exact:true}).waitFor();
  await page.locator('nav [data-view=support]').click();
  await page.getByText('No support messages yet.',{exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.locator('nav [data-view=overview]').click();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile horizontal overflow');
  await page.locator('#logout').click();
  await page.locator('#login').waitFor({state:'visible'});
  if(errors.length)throw Error(errors.join('; '));
  await browser.close();console.log('Browser workflow passed: login, empty live dashboard, enrollment, search, policy update, fleet update, banking configuration, messaging receipts, support and logout.');
})().catch(e=>{console.error(e);process.exit(1);});
